# 8 Puzzle using DFS

initial = (1, 2, 3,
           0, 4, 6,
           7, 5, 8)

goal = (1,2,3,
        4,5,6,
        7,8,0)


def print_puzzle(state):
    for i in range(0, 9, 3):
        print(state[i:i+3])
    print()


def get_moves(state):
    blank = state.index(0)
    row, col = divmod(blank, 3)

    moves = []

    if row > 0:
        moves.append(("Up", blank - 3))

    if row < 2:
        moves.append(("Down", blank + 3))

    if col > 0:
        moves.append(("Left", blank - 1))

    if col < 2:
        moves.append(("Right", blank + 1))

    return moves


def make_move(state, new_pos):
    blank = state.index(0)

    s = list(state)
    s[blank], s[new_pos] = s[new_pos], s[blank]

    return tuple(s)


# DFS with depth limit
def dfs(state, depth, path, visited):

    if state == goal:
        return path

    if depth == 0:
        return None

    visited.add(state)

    for action, new_pos in get_moves(state):

        new_state = make_move(state, new_pos)

        if new_state not in visited:

            result = dfs(
                new_state,
                depth - 1,
                path + [action],
                visited
            )

            if result is not None:
                return result

    visited.remove(state)

    return None


# Try DFS with increasing limits
def solve_dfs():

    for limit in range(1, 31):

        result = dfs(
            initial,
            limit,
            [],
            set()
        )

        if result is not None:
            return result, limit

    return None, None


# ---------------- MAIN ----------------

print("INITIAL STATE:")
print_puzzle(initial)

print("GOAL STATE:")
print_puzzle(goal)

print("----- DFS -----")

solution, depth = solve_dfs()

if solution:
    print("Solution found!")
    print("Depth:", depth)
    print("Number of moves:", len(solution))
    print("Moves:")
    print(" -> ".join(solution))
else:
    print("No solution found.")