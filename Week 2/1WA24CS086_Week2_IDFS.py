# 8 Puzzle using Iterative Deepening Search (IDS)
initial = (1,2,3,
           0,4,6,
           7,5,8)

goal = (1,2,3,
        4,5,6,
        7,8,0)


# Display puzzle
def print_puzzle(state):
    for i in range(0, 9, 3):
        print(state[i:i+3])
    print()


# Generate possible moves
def get_moves(state):
    blank = state.index(0)
    row, col = divmod(blank, 3)

    moves = []

    if row > 0:
        moves.append(("Up", blank - 3))

    if row < 2:
        moves.append(("Down", blank + 3))

    if col > 0:
        moves.append(("Left", blank - 1))

    if col < 2:
        moves.append(("Right", blank + 1))

    return moves


# Make a move
def make_move(state, new_pos):
    blank = state.index(0)

    s = list(state)
    s[blank], s[new_pos] = s[new_pos], s[blank]

    return tuple(s)


# Depth Limited DFS
def depth_limited_search(state, depth, path, visited):

    # Goal test
    if state == goal:
        return path

    # Depth limit reached
    if depth == 0:
        return None

    visited.add(state)

    for action, new_pos in get_moves(state):

        new_state = make_move(state, new_pos)

        # Avoid cycles in current path
        if new_state not in visited:

            path.append(action)

            result = depth_limited_search(
                new_state,
                depth - 1,
                path,
                visited
            )

            if result is not None:
                return result

            path.pop()

    visited.remove(state)

    return None


# Iterative Deepening Search
def ids():

    for depth in range(31):

        print("Searching at depth:", depth)

        result = depth_limited_search(
            initial,
            depth,
            [],
            set()
        )

        if result is not None:
            return result

    return None


# ---------------- MAIN ----------------

print("INITIAL STATE:")
print_puzzle(initial)

print("GOAL STATE:")
print_puzzle(goal)

print("----- IDS -----")

solution = ids()

if solution:
    print("\nSolution found!")
    print("Number of moves:", len(solution))
    print("Moves:")
    print(" -> ".join(solution))
else:
    print("No solution found.")