import random

# Randomly create the environment
environment = {
    "A": random.choice(["Clean", "Dirty"]),
    "B": random.choice(["Clean", "Dirty"])
}

# Start at a random location
location = random.choice(["A", "B"])

print("Initial Environment:", environment)
print("Starting Location:", location)

# Simple Reflex Agent
def vacuum_agent(location, status):
    if status == "Dirty":
        return "Pick the Dirt"
    elif location == "A":
        return "Right"
    else:
        return "Left"


# Run the agent
while True:
    status = environment[location]

    print("\nPercept:", [location, status])

    action = vacuum_agent(location, status)
    print("Action:", action)

    if action == "Pick the Dirt":
        environment[location] = "Clean"
        print("Dirt cleaned!")

    elif action == "Right":
        location = "B"

    elif action == "Left":
        location = "A"

    # Stop when both locations are clean
    if environment["A"] == "Clean" and environment["B"] == "Clean":
        print("\nFinal Environment:", environment)
        print("Both locations are clean!")
        break