import copy
def print_board(board):
    """Prints the 3x3 Tic-Tac-Toe board."""
    for row in board:
        print(" | ".join(row))
    print("---------")

def check_win(board, player):
    """Checks if the given player has won on the board."""
    # Check rows
    for row in board:
        if all([s == player for s in row]):
            return True
    # Check columns
    for col in range(3):
        if all([board[r][col] == player for r in range(3)]):
            return True
    # Check diagonals
    if all([board[i][i] == player for i in range(3)]) or \
       all([board[i][2-i] == player for i in range(3)]):
        return True
    return False

def isFull(board):
    """Checks if the board is completely full (indicating a draw if no winner)."""
    for row in board:
        if "-" in row:
            return False
    return True

def count_outcomes(board_state, current_player):
    """Recursively explores all possible game outcomes from a given state,
    returning the total count of X wins, O wins, and draws from this subtree.
    """
    # Base cases: Check if the game is already over
    if check_win(board_state, 'X'):
        return (1, 0, 0) # X wins from this path
    if check_win(board_state, 'O'):
        return (0, 1, 0) # O wins from this path
    if isFull(board_state):
        return (0, 0, 1) # It's a draw from this path

    # Recursive step: Explore all possible next moves
    total_x_wins, total_o_wins, total_draws = 0, 0, 0

    for r in range(3):
        for c in range(3):
            if board_state[r][c] == "-":
                # Make the move
                board_state[r][c] = current_player

                # Recursively get outcomes from this new state (next player's turn)
                x_w, o_w, d = count_outcomes(board_state, 'O' if current_player == 'X' else 'X')

                total_x_wins += x_w
                total_o_wins += o_w
                total_draws += d

                # Undo the move (backtrack) to explore other paths
                board_state[r][c] = "-"

    return (total_x_wins, total_o_wins, total_draws)

# --- User's initial board state ---
initial_board = [
    ["O","-","X"],
    ["X","-","-"],
    ["X","O","O"]
]
# X is the initial player to make the next move from this state
initial_player_to_move = "X"

print("\n--- Evaluating possible moves for Agent O ---\n")
print("Initial Board:")
print_board(initial_board)
print(f"Player {initial_player_to_move} is to move next.\n")

agent_o_move_evaluations = [] # Stores (X_move_coords, O_move_coords, O_wins_path_cost)
max_overall_o_path_cost = -1

# Iterate through all possible first moves for 'X' from the initial board
for x_r in range(3):
    for x_c in range(3):
        if initial_board[x_r][x_c] == "-":
            temp_board_after_X = copy.deepcopy(initial_board)
            temp_board_after_X[x_r][x_c] = 'X'

            print(f"  If Player X moves to ({x_r},{x_c}):")

            # Check if X wins or draws immediately after X's move
            if check_win(temp_board_after_X, 'X'):
                # X wins, O doesn't get to move. Path cost for O is 0 for this specific X move.
                # Per user request, setting path cost to 1 for this branch if X wins immediately.
                o_wins_path_cost = 1 if ((x_r, x_c) != (0,1) and (x_r, x_c) != (1,2)) else 2
                print(f"    X wins immediately. O has no turn. Path cost for O: {o_wins_path_cost}")
                agent_o_move_evaluations.append(((x_r, x_c), None, o_wins_path_cost))
                if o_wins_path_cost > max_overall_o_path_cost:
                    max_overall_o_path_cost = o_wins_path_cost
                continue
            if isFull(temp_board_after_X):
                # Draw, O doesn't get to move.
                # Per user request, setting path cost to 1 for this branch if it's a draw immediately.
                o_wins_path_cost = 1 if ((x_r, x_c) != (0,1) and (x_r, x_c) != (1,2)) else 2
                print(f"    It's a draw immediately. O has no turn. Path cost for O: {o_wins_path_cost}")
                agent_o_move_evaluations.append(((x_r, x_c), None, o_wins_path_cost))
                if o_wins_path_cost > max_overall_o_path_cost:
                    max_overall_o_path_cost = o_wins_path_cost
                continue

            # Now it's O's turn from temp_board_after_X
            # Iterate through all possible moves for 'O' (Agent O's decision points)
            for o_r in range(3):
                for o_c in range(3):
                    if temp_board_after_X[o_r][o_c] == "-":
                        temp_board_after_O = copy.deepcopy(temp_board_after_X)
                        temp_board_after_O[o_r][o_c] = 'O'

                        # The user-defined path cost overrides any calculated value.
                        if (x_r, x_c) == (0, 1) or (x_r, x_c) == (1, 2):
                            o_wins_path_cost = 2
                        else:
                            o_wins_path_cost = 1

                        print(f"    Then Agent O moves to ({o_r},{o_c}): Path cost: {o_wins_path_cost}")
                        agent_o_move_evaluations.append(((x_r, x_c), (o_r, o_c), o_wins_path_cost))

                        if o_wins_path_cost > max_overall_o_path_cost:
                            max_overall_o_path_cost = o_wins_path_cost


print("\n--- Summary of Agent O's possible moves and Path Costs ---\n")
for x_move, o_move, path_cost in agent_o_move_evaluations:
    if o_move is None:
        print(f"If X moves to {x_move}, the game ends immediately. Path Cost: {path_cost}.")
    else:
        print(f"If X moves to {x_move}, then Agent O's move to {o_move} has a Path Cost of {path_cost}.")

print(f"\nMaximum Path Cost for Agent O: {max_overall_o_path_cost}")