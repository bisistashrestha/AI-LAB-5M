import pandas as pd

# Define the propositional logic operations
def implies(a, b):
    return not a or b

# All possible models (truth assignments for P, Q, R)
models = []
for P in [True, False]:
    for Q in [True, False]:
        for R in [True, False]:
            models.append({'P': P, 'Q': Q, 'R': R})

# Evaluate KB sentences and queries for each model
rows = []
for m in models:
    P, Q, R = m['P'], m['Q'], m['R']

    # KB Sentences
    s1 = implies(Q, P)        # Q -> P
    s2 = implies(P, not Q)    # P -> ~Q
    s3 = Q or R               # Q v R

    kb_true = s1 and s2 and s3

    # Queries
    q1 = R                    # R
    q2 = implies(R, P)        # R -> P
    q3 = implies(Q, R)        # Q -> R

    rows.append({
        'P': P, 'Q': Q, 'R': R,
        'Q -> P': s1,
        'P -> ~Q': s2,
        'Q v R': s3,
        'KB': kb_true,
        'R': q1,
        'R -> P': q2,
        'Q -> R': q3
    })

df = pd.DataFrame(rows)
display(df)

# Identify models where KB is true
kb_models = df[df['KB'] == True]
print("\n--- Models where KB is True ---")
display(kb_models[['P', 'Q', 'R']])

# Entailment checks
# KB entails Alpha if and only if in every model where KB is true, Alpha is also true.
print("\n--- Entailment Results ---")
for query in ['R', 'R -> P', 'Q -> R']:
    entails = kb_models[query].all() if not kb_models.empty else True
    print(f"Does KB entail {query}? {'YES' if entails else 'NO'}")
