# 8-Puzzle using A* Search
import heapq

initial = (2,8,3,
           1,6,4,
           7,0,5)

goal = (1,2,3,
        8,0,4,
        7,6,5)


# Display puzzle
def print_puzzle(state):
    for i in range(0, 9, 3):
        print(state[i:i+3])
    print()


# Manhattan Distance
def heuristic(state):
    distance = 0

    for i in range(9):

        if state[i] == 0:
            continue

        goal_pos = goal.index(state[i])

        row1, col1 = divmod(i, 3)
        row2, col2 = divmod(goal_pos, 3)

        distance += abs(row1 - row2) + abs(col1 - col2)

    return distance


# Generate possible moves
def get_moves(state):

    blank = state.index(0)

    row, col = divmod(blank, 3)

    moves = []

    if row > 0:
        moves.append(("Up", blank - 3))

    if row < 2:
        moves.append(("Down", blank + 3))

    if col > 0:
        moves.append(("Left", blank - 1))

    if col < 2:
        moves.append(("Right", blank + 1))

    return moves


# Make a move
def make_move(state, new_pos):

    blank = state.index(0)

    s = list(state)

    s[blank], s[new_pos] = s[new_pos], s[blank]

    return tuple(s)


# A* Search
def astar():

    # Priority queue:
    # (f, g, state)

    pq = []

    h = heuristic(initial)

    heapq.heappush(pq, (h, 0, initial))

    # Best cost found for each state
    g_cost = {initial: 0}

    # Parent information
    parent = {}

    while pq:

        f, g, state = heapq.heappop(pq)

        # Goal found
        if state == goal:

            path = []

            while state != initial:
                previous, action = parent[state]

                path.append(action)

                state = previous

            path.reverse()

            return path

        # Generate next states
        for action, new_pos in get_moves(state):

            new_state = make_move(state, new_pos)

            new_g = g + 1

            # Only keep better paths
            if new_state not in g_cost or new_g < g_cost[new_state]:

                g_cost[new_state] = new_g

                h = heuristic(new_state)

                f = new_g + h

                parent[new_state] = (state, action)

                heapq.heappush(
                    pq,
                    (f, new_g, new_state)
                )

    return None


# ---------------- MAIN ----------------

print("INITIAL STATE:")
print_puzzle(initial)

print("GOAL STATE:")
print_puzzle(goal)

print("----- A* SEARCH -----")

solution = astar()

if solution:

    print("Solution found!")
    print("Number of moves:", len(solution))

    print("Moves:")
    print(" -> ".join(solution))

else:

    print("No solution found.")