def run_forward_chaining():
    # Initial base facts (known constants and relationships)
    facts = {
        "American(Robert)",
        "Enemy(A, America)",
        "Missile(M1)",
        "Owns(A, M1)"
    }

    # Rule representations
    # Rules are represented as (List of Antecedents, Consequent)
    # Variables are represented as strings starting with lowercase letters: x, y, z
    rules = [
        # Rule 1: Missile(x) -> Weapon(x)
        (["Missile(x)"], "Weapon(x)"),

        # Rule 2: Enemy(x, America) -> Hostile(x)
        (["Enemy(x, America)"], "Hostile(x)"),

        # Rule 3: Missile(x) ^ Owns(A, x) -> Sells(Robert, x, A)
        (["Missile(x)", "Owns(A, x)"], "Sells(Robert, x, A)"),

        # Rule 4: American(x) ^ Weapon(y) ^ Sells(x, y, z) ^ Hostile(z) -> Criminal(x)
        (["American(x)", "Weapon(y)", "Sells(x, y, z)", "Hostile(z)"], "Criminal(x)")
    ]

    def parse_literal(lit):
        # Helper to parse "Predicate(arg1, arg2)" -> ('Predicate', ['arg1', 'arg2'])
        name, args_str = lit.split('(')
        args = [a.strip() for a in args_str[:-1].split(',')]
        return name, args

    def match_and_substitute(antecedents, facts):
        # Basic unification and substitution generator for the rules
        # Returns list of successful substitutions (dict of var -> value)
        results = [{}]

        for ant in antecedents:
            ant_name, ant_args = parse_literal(ant)
            new_results = []
            for res in results:
                for fact in facts:
                    fact_name, fact_args = parse_literal(fact)
                    if ant_name != fact_name or len(ant_args) != len(fact_args):
                        continue

                    # Check if unification is possible with the current substitution 'res'
                    temp_res = dict(res)
                    match = True
                    for a, f in zip(ant_args, fact_args):
                        if a[0].islower():  # Variable
                            if a in temp_res:
                                if temp_res[a] != f:
                                    match = False
                                    break
                            else:
                                temp_res[a] = f
                        else:  # Constant
                            if a != f:
                                match = False
                                break
                    if match:
                        new_results.append(temp_res)
            results = new_results
        return results

    def apply_subst(consequent, subst):
        name, args = parse_literal(consequent)
        subst_args = [subst[a] if a in subst else a for a in args]
        return f"{name}({', '.join(subst_args)})"

    print("--- STARTING FORWARD CHAINING INFERENCE ---")
    print(f"Initial Facts (KB): {sorted(list(facts))}\n")

    iteration = 1
    new_facts_inferred = True

    while new_facts_inferred:
        print(f"--- Iteration {iteration} ---")
        new_facts_inferred = False
        new_this_round = set()

        for r_idx, (antecedents, consequent) in enumerate(rules):
            substitutions = match_and_substitute(antecedents, facts)
            for subst in substitutions:
                inferred = apply_subst(consequent, subst)
                if inferred not in facts and inferred not in new_this_round:
                    print(f"Rule {r_idx + 1} triggered with {subst} => Inferred: {inferred}")
                    new_this_round.add(inferred)
                    new_facts_inferred = True

        if new_this_round:
            facts.update(new_this_round)
            print(f"Facts added in this iteration: {sorted(list(new_this_round))}")
            print(f"Updated KB: {sorted(list(facts))}\n")
            if any("Criminal(Robert)" in f for f in new_this_round):
                print("SUCCESS: 'Criminal(Robert)' has been proven!")
                break
        else:
            print("No new facts could be inferred in this iteration. Forward Chaining stops.\n")
            break

        iteration += 1

run_forward_chaining()
